export function languageCurrency(language: Language) {
  if (language === "es") return "MXN" as const;
  if (language === "en") return "USD" as const;
  if (language === "pt") return "BRL" as const;
  if (language === "fr" || language === "de" || language === "it") return "EUR" as const;
  return "USD" as const;
}

